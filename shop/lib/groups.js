// Одяг/взуття: військові бренди → військовий одяг, решта → цивільний.
const CLOTHING_WORDS = ['рукавиц', 'балаклав', 'бейсболк', 'панам', 'шапк', 'шкарпет', 'куртк', 'штан', 'футболк', 'кофт', 'фліс', 'худі'];

export function groupOf(p) {
  const c = String(p.category || '').toLowerCase();
  const v = p.vendor;
  for (const [group, test] of RULES) {
    if (!test(c, v)) continue;
    // одяг, що потрапив у «Тактичні аксесуари» постачальника, показуємо серед одягу
    if (group === 'Тактичне спорядження і захист' && !has(c, 'захисту', 'шолом') && has(String(p.title || '').toLowerCase(), ...CLOTHING_WORDS)) {
      return 'Військовий і тактичний одяг';
    }
    return group;
  }
  if (MILITARY_VENDORS.has(v)) return 'Військовий і тактичний одяг';
  if (v === 'Secret Shop' || has(c, 'одяг', 'костюм', 'сумк', 'рюкзак')) return 'Одяг';
  return 'Інше';
}

