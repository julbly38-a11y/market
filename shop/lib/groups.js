// Одяг/взуття: військові бренди → військовий одяг, решта → цивільний.
export function groupOf(p) {
  const c = String(p.category || '').toLowerCase();
  const v = p.vendor;
  for (const [group, test] of RULES) if (test(c, v)) return group;
  if (MILITARY_VENDORS.has(v)) return 'Військовий і тактичний одяг';
  if (v === 'Secret Shop' || has(c, 'одяг', 'костюм', 'сумк', 'рюкзак')) return 'Одяг';
  return 'Інше';
}
