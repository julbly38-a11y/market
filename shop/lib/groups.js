export function typeRank(group, type) {
  const order = DISPLAY_ORDER[group] || (TYPE_RULES[group] || []).map(([t]) => t);
  const i = order.indexOf(type);
  return i >= 0 ? i : type === OTHER ? 999 : 500;
}
