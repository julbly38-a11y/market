export function typeOf(p, group = groupOf(p)) {
  const rules = TYPE_RULES[group];
  const text = `${p.category || ''} ${p.title || ''}`.toLowerCase();
  if (rules) {
    for (const [type, words] of rules) if (words.some((w) => text.includes(w))) return type;
    return OTHER;
  }
  // решта груп: беремо категорію постачальника, прибираючи службові («Інше» тощо)
  const c = String(p.category || '').trim();
  return c && c.toLowerCase() !== 'інше' ? c : OTHER;
}

