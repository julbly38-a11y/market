const CAP_DESC = 3;
const lc = (s) => String(s || '').toLowerCase();

const esc = (w) => w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const reCache = new Map();
// Ключ збігається лише на початку слова: «куля» не знайдеться в «окуляри», «шина» — в «машина».
function re(w) {
  let r = reCache.get(w);
  if (!r) {
    r = new RegExp(`(?<![\\p{L}\\p{N}])${esc(w.trim())}`, 'u');
    reCache.set(w, r);
  }
  return r;
}
function hits(text, words) {
  let n = 0;
  for (const w of words) if (re(w).test(text)) n++;
  return n;
}

export function scoreLeaf(leaf, title, category, desc) {
  if (leaf.not.length && (hits(title, leaf.not) > 0 || hits(category, leaf.not) > 0)) return -20;
  const t = Math.min(hits(title, leaf.kw), 2);
  const c = Math.min(hits(category, leaf.kw), 2);
  const d = Math.min(hits(desc, leaf.kw), CAP_DESC);
  return t * 6 + c * 3 + d;
}

// Класифікує товар поза військовими групами. legacyGroup — група зі старих правил (бонус, щоб не стрибати без причини).
export function classifyRest(p, desc, legacyGroup) {
  const title = lc(p.title);
  const category = lc(p.category);
  const d = lc(desc).slice(0, 500);
  const legacy = LEGACY_GROUP[legacyGroup] || legacyGroup;
  let best = null;
  for (const leaf of LEAVES) {
    let s = scoreLeaf(leaf, title, category, d);
    if (s <= 0) continue;
    if (leaf.group === legacy) s += 2;
    else if (s < 5) continue; // перенос в іншу групу лише за збігом у назві
    if (!best || s > best.s) best = { s, group: leaf.group, type: leaf.type };
  }
  if (best && best.s >= 3) return { g: best.group, t: best.type };
  return { g: legacy, t: 'Інше' };
}

export function typeOrder(group) {
  const order = [];
  for (const l of LEAVES) if (l.group === group && !order.includes(l.type)) order.push(l.type);
  return order;
}
